func haversineKm(lat1, lng1, lat2, lng2 float64) float64 {
	const r = 6371.0
	dLat := (lat2 - lat1) * math.Pi / 180
	dLng := (lng2 - lng1) * math.Pi / 180
	a := math.Sin(dLat/2)*math.Sin(dLat/2) +
		math.Cos(lat1*math.Pi/180)*math.Cos(lat2*math.Pi/180)*math.Sin(dLng/2)*math.Sin(dLng/2)
	return 2 * r * math.Asin(math.Min(1, math.Sqrt(a)))
}

// NearestChinaCity 从离线中国城市表中匹配距离最近的城市名称（220 公里内视为有效）。
func NearestChinaCity(lat, lng float64) (city string, regionCode string, ok bool) {
	bestDist := math.Inf(1)
	var best chinaCityCoord
	for _, c := range chinaCityTable {
		if d := haversineKm(lat, lng, c.Lat, c.Lng); d < bestDist {
			bestDist = d
			best = c
		}
	}
	if bestDist <= 220 {
		return best.City, best.RegionCode, true
	}
	return "", "", false
}

// ReverseGeocodeCity 将 GPS 经纬度解析为友好中文城市/区县名称，在线解析超时或失败时自动回退至离线中国城市表。
func (c *Client) ReverseGeocodeCity(ctx context.Context, lat, lng float64) string {
	if c != nil {
		base := strings.TrimRight(c.GeocodeBaseURL, "/")
		if base == "" {
			base = "https://api.bigdatacloud.net"
		}
		subCtx, cancel := context.WithTimeout(ctx, 3500*time.Millisecond)
		u := fmt.Sprintf("%s/data/reverse-geocode-client?latitude=%.5f&longitude=%.5f&localityLanguage=zh", base, lat, lng)
		var resp bigDataCloudResp
		err := c.getJSON(subCtx, u, nil, &resp)
		cancel()
		if err == nil {
			if name := formatReverseGeocodeName(resp); name != "" {
				return name
			}
		}
	}
	if city, _, ok := NearestChinaCity(lat, lng); ok {
		return city
	}
	return fmt.Sprintf("%.3f, %.3f", lat, lng)
}

func formatReverseGeocodeName(r bigDataCloudResp) string {
	prov := strings.TrimSpace(r.PrincipalSubdivision)
	city := strings.TrimSpace(r.City)
	loc := strings.TrimSpace(r.Locality)

	parts := make([]string, 0, 2)
	addPart := func(v string) {
		v = strings.TrimSpace(v)
		if v == "" {
			return
		}
		for _, p := range parts {
			if p == v || strings.Contains(p, v) || strings.Contains(v, p) {
				return
			}
		}
		parts = append(parts, v)
	}

	if city != "" {
		addPart(city)
		if loc != "" && loc != city {
			addPart(loc)
		}
	} else if prov != "" {
		addPart(prov)
		if loc != "" && loc != prov {
			addPart(loc)
		}
	} else if loc != "" {
		addPart(loc)
	}
	if len(parts) == 0 {
		return ""
	}
	return strings.Join(parts, " ")
}
