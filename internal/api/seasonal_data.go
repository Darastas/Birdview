// SeasonalBirdsByRegionAndMonth 按地区码与月份筛选并返回按四大时令分类归组的指南列表。
func SeasonalBirdsByRegionAndMonth(regionCode string, month int) map[model.SeasonalPhase][]model.SeasonalBird {
	zone := model.RegionCodeToEcoZone(regionCode)
	grouped := map[model.SeasonalPhase][]model.SeasonalBird{
		model.PhaseLeaving:      nil,
		model.PhaseInSeason:     nil,
		model.PhaseJustArrived:  nil,
		model.PhaseArrivingSoon: nil,
	}
	for _, b := range SeasonalBirdGuideDatabase {
		ph := b.PhaseFor(zone, month)
		if ph != model.PhaseAbsent {
			grouped[ph] = append(grouped[ph], b)
		}
	}
	return grouped
}

// FindSeasonalBirdByCode 按 eBird SpeciesCode 查找内置时令指南档案。
func FindSeasonalBirdByCode(code string) (model.SeasonalBird, bool) {
	for _, b := range SeasonalBirdGuideDatabase {
		if b.SpeciesCode == code {
			return b, true
		}
	}
	return model.SeasonalBird{}, false
}
